package a07ex01;

// Classe Fabricante
public class Fabricante {
    private String nome;

    // Construtor vazio
    public Fabricante() {
    }

    // Construtor completo
    public Fabricante(String nome) {
        this.nome = nome;
    }

    // Getters e Setters
    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }
}
